<?php

declare(strict_types=1);

namespace Aoc;

use DateTimeImmutable;
use DateTimeZone;

/**
 * Which puzzle days exist, and where their files live.
 *
 * This replaces the day-release logic that used to sit in the old app's
 * config/challenges.php, which computed it on every config load and wrote stub
 * files to disk as a side effect. Here it is a pure calculation.
 */
final class Calendar
{
    public const FIRST_YEAR = 2015;

    public const LAST_DAY = 25;

    /** Advent of Code unlocks puzzles at midnight EST. */
    private const RELEASE_TZ = 'America/New_York';

    /**
     * Every (year, day) pair that has actually been released.
     *
     * Past years give all 25 days. The current year gives only the days
     * unlocked so far, which is none outside December.
     *
     * @return list<array{int, int}>
     */
    public static function releasedDays(?DateTimeImmutable $now = null): array
    {
        $now = ($now ?? new DateTimeImmutable('now'))
            ->setTimezone(new DateTimeZone(self::RELEASE_TZ));

        $thisYear = (int) $now->format('Y');
        $days = [];

        for ($year = self::FIRST_YEAR; $year <= $thisYear; $year++) {
            $last = $year < $thisYear
                ? self::LAST_DAY
                : self::releasedDaysInCurrentYear($now);

            for ($day = 1; $day <= $last; $day++) {
                $days[] = [$year, $day];
            }
        }

        return $days;
    }

    private static function releasedDaysInCurrentYear(DateTimeImmutable $now): int
    {
        if ((int) $now->format('n') !== 12) {
            return 0;
        }

        return min((int) $now->format('j'), self::LAST_DAY);
    }

    /** Collection item slug, e.g. "2024-01". */
    public static function slug(int $year, int $day): string
    {
        return sprintf('%04d-%02d', $year, $day);
    }

    /** Path to the problem file, relative to the repo root. */
    public static function path(int $year, int $day): string
    {
        return 'source/_problems/'.self::slug($year, $day).'.md';
    }

    /** Canonical puzzle URL. Derived, never stored, so it cannot drift. */
    public static function link(int $year, int $day): string
    {
        return sprintf('https://adventofcode.com/%d/day/%d', $year, $day);
    }

    /**
     * Was this solved outside its own event?
     *
     * The event runs Dec 1-25 of its year. Anything later -- including a day
     * solved in a subsequent December -- counts as retroactive. Returns false
     * when the date is unknown, so an unsolved day is not labelled.
     */
    public static function isRetroactive(?string $solvedAt, int $year): bool
    {
        if ($solvedAt === null || $solvedAt === '') {
            return false;
        }

        $date = DateTimeImmutable::createFromFormat('!Y-m-d', $solvedAt);

        if ($date === false) {
            return false;
        }

        return $date < new DateTimeImmutable("{$year}-12-01")
            || $date > new DateTimeImmutable("{$year}-12-25");
    }

    /**
     * Stub titles were generated by the old app for days that were never
     * attempted, in two formats over the years. They carry no information, so
     * they are dropped rather than migrated.
     */
    public static function isStubTitle(string $title): bool
    {
        $title = trim($title);

        return $title === ''
            || preg_match('/^Day\s*\d+\s*-\s*\d{4}$/', $title) === 1
            || preg_match('/^Day\s*\d+\s*:$/', $title) === 1;
    }
}
